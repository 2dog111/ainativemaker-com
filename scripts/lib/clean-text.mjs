// Общая нормализация текста для импортов дневника: переводы строк и пробелы.
// Используется и импортом канала (scripts/import-diary.mjs), и импортом закрытого чата
// (scripts/import-chat-diary.mjs), чтобы обе части хронологии приводились одинаково.
// Мат не смягчается: фильтр снят 08.10.2026 по слову владельца («мат допустим везде»),
// закрытые им «…» в опубликованных записях восстановлены по исходникам.

export function cleanText(value) {
  const text = value
    .normalize("NFC")
    .replace(/\r\n?/g, "\n")
    .replace(/[ \t]+([,.;:!?])/g, "$1")
    .replace(/[ \t]{2,}/g, " ")
    .replace(/ *\n */g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return { text, edits: [] };
}
