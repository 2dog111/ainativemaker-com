// Общая очистка текста для импортов дневника: смягчение мата и нормализация пробелов.
// Используется и импортом канала (scripts/import-diary.mjs), и импортом закрытого чата
// (scripts/import-chat-diary.mjs), чтобы обе части хронологии чистились одинаково.

export const replacements = [
  [/вайбдрочеры/giu, "вайб-кодеры"],
  [/вайбдрочеров/giu, "вайб-кодеров"],
  [/вайбдрочерами/giu, "вайб-кодерами"],
  [/вайбдрочингу/giu, "вайб-кодингу"],
  [/вайбдрочинга/giu, "вайб-кодинга"],
  [/вайбдрочингом/giu, "вайб-кодингом"],
  [/вайбдрочинг/giu, "вайб-кодинг"],
  [/навайбдрочил/giu, "навайбкодил"],
  [/вайбдрочил/giu, "вайбкодил"],
  [/вайбдрочу/giu, "вайбкодю"],
  [/вайбдроч/giu, "вайбкод"],
  [/(?<![А-Яа-яЁё])(?:бля[\p{L}-]*|сук(?:а|и)?|(?:осто|от|с)?пизд[\p{L}-]*|(?:по)?пизж[\p{L}-]*|(?:[взнпосу]?[ъь]?[её]б(?:а|у|л|н|с|аш)[\p{L}-]*|выеб[\p{L}-]*|(?:под)?заеб[\p{L}-]*|доеб[\p{L}-]*|изъеб[\p{L}-]*|мозгоеб[\p{L}-]*|наеб[\p{L}-]*|наёбыва[\p{L}-]*|отъеб[\p{L}-]*|поебать|проеб[\p{L}-]*|разъеб[\p{L}-]*|съеб[\p{L}-]*|уеб[\p{L}-]*|злоебуч[\p{L}-]*|ебейш[\p{L}-]*|ебуч[\p{L}-]*|[её]бан[\p{L}-]*|заебис[\p{L}-]*|(?:на|за|по)?хуеверт[\p{L}-]*|хуев[аоы][\p{L}-]*|неебаца|шароёб[\p{L}-]*)|(?:[взднпосу]?(?:ху[йеяи]|хуе|хуя)[\p{L}-]*|ахуе[\p{L}-]*|ахулиард[\p{L}-]*|ахуй|доху[яи][\p{L}-]*|захуя[\p{L}-]*|наху[йяи][\p{L}-]*|нихуя|неху[\p{L}-]*|охуе[\p{L}-]*|поху[\p{L}-]*)|(?:от)?пидор[\p{L}-]*|долбаёб[\p{L}-]*|(?:вз|за|по|под|раз|суб)?дроч[\p{L}-]*|говн[\p{L}-]*|(?:мудак|мудил)[\p{L}-]*|(?:рукожоп|хитрожоп|жоп)[\p{L}-]*|(?:за|в|на)?сра(?:ть|н|л)[\p{L}-]*|(?:под)?залуп[\p{L}-]*|(?:обо)?ссан[\p{L}-]*|шлюх[\p{L}-]*|хули|хуле|ёбта|ёпта|епта)(?![А-Яа-яЁё])/giu, "…"]
];

export function cleanText(value) {
  let text = value.normalize("NFC").replace(/\r\n?/g, "\n");
  const edits = [];
  for (const [pattern, replacement] of replacements) {
    if (pattern.test(text)) {
      pattern.lastIndex = 0;
      text = text.replace(pattern, replacement);
      edits.push("profanity");
    }
    pattern.lastIndex = 0;
  }
  text = text
    .replace(/[ \t]+([,.;:!?])/g, "$1")
    .replace(/[ \t]{2,}/g, " ")
    .replace(/(?:…\s*){2,}/g, "… ")
    .replace(/ *\n */g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return { text, edits: [...new Set(edits)] };
}
