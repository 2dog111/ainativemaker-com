// Ссылки на персональные посты, приглашения и партнёрские программы снимаются
// даже на известных хостах: это не ссылка на сервис, а ссылка на человека.
const PERSONAL_LINK_MARKERS = [/\/status\//u, /\/share\//u, /[?&]aff=/u, /invitation_code=/u];

const linkHost = (url) => {
  try {
    return new URL(url).hostname.toLowerCase();
  } catch {
    return "";
  }
};

export const isAllowedLink = (url) => {
  const host = linkHost(url);
  if (!ALLOWED_LINK_HOSTS.includes(host)) return false;
  return !PERSONAL_LINK_MARKERS.some((marker) => marker.test(url));
};

