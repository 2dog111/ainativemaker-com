const applyRules = (value, rules) => rules.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), value);

// Снимает URL, оставляя читаемый текст. Markdown-ссылка теряет адрес и
// сохраняет подпись; голый адрес удаляется вместе с осиротевшей пунктуацией.
const stripLinks = (value) => {
  let text = value.replace(/\[([^\]\n]+)\]\((https?:\/\/[^\s)]+)\)/gu, (match, label, url) =>
    isAllowedLink(url) ? match : label
  );

  text = text.replace(/https?:\/\/[^\s<]+/gu, (url) => {
    // Хвостовая пунктуация не входит в адрес.
    const trimmed = url.replace(/[.,;:!?)»"']+$/u, "");
    const tail = url.slice(trimmed.length);
    return isAllowedLink(trimmed) ? url : tail;
  });

  // Пробелы выправляются только там, где адрес действительно сняли: в остальном
  // текст записи должен дойти до страницы ровно таким, каким он был написан.
  if (text === value) return text;

  return text
    // Снятый адрес оставляет после себя пробел перед знаком препинания.
    .replace(/[ \t]+([,.;:!?)])/gu, "$1")
    .replace(/[ \t]+$/gmu, "")
    .replace(/^[ \t]*[-—–•]\s*$/gmu, "")
    .replace(/\n{3,}/gu, "\n\n")
    .trim();
};

export const sanitizeParagraph = (paragraph) => applyRules(applyRules(stripLinks(paragraph), NAME_RULES), PLACE_RULES);

export const sanitizePost = (post) => ({
  ...post,
  paragraphs: post.paragraphs.map(sanitizeParagraph).filter((paragraph) => paragraph.length > 0)
});

export const sanitizePosts = (posts) => posts.map(sanitizePost);
